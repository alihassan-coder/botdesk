/**
 * Builds every logo file. Run from the repo root:
 *   node docs/design/logo/tools/build.mjs
 *
 * 1. Serves docs/design/logo over http (fonts load over the network, so file:// won't do).
 * 2. Runs export.html's build() in Chrome (Playwright from apps/web).
 * 3. Writes svg/, png/, favicon.ico, and the web app's copies (favicon, icons, logo-data.ts).
 */
import { createServer } from "node:http";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, extname } from "node:path";
import { fileURLToPath } from "node:url";

const tools = dirname(fileURLToPath(import.meta.url));
const logo = join(tools, "..");
const repo = join(logo, "../../..");
const require = createRequire(join(repo, "apps/web/package.json"));
const { chromium } = require("@playwright/test");

const server = createServer((req, res) => {
  try {
    const path = join(logo, decodeURIComponent(req.url.split("?")[0]));
    const file = readFileSync(path); // throws (→ 404) before any headers go out
    res.writeHead(200, { "content-type": extname(path) === ".html" ? "text/html" : "application/octet-stream" });
    res.end(file);
  } catch {
    res.writeHead(404).end();
  }
}).listen(0);
const port = server.address().port;

const browser = await chromium.launch({ channel: "chrome" });
const page = await browser.newPage();
await page.goto(`http://127.0.0.1:${port}/tools/export.html`);
const { svgs, pngs, web } = await page.evaluate(() => window.build());
await browser.close();
server.close();

mkdirSync(join(logo, "svg"), { recursive: true });
mkdirSync(join(logo, "png"), { recursive: true });
for (const [name, text] of Object.entries(svgs)) writeFileSync(join(logo, "svg", name), text);
const blobs = Object.fromEntries(Object.entries(pngs).map(([n, b64]) => [n, Buffer.from(b64, "base64")]));
for (const [name, blob] of Object.entries(blobs)) if (!name.startsWith("favicon-")) writeFileSync(join(logo, "png", name), blob);

// favicon.ico: PNG-compressed 16, 32 and 48 px entries (every current browser reads these).
const sizes = [16, 32, 48];
const header = Buffer.alloc(6);
header.writeUInt16LE(0, 0); header.writeUInt16LE(1, 2); header.writeUInt16LE(sizes.length, 4);
let offset = 6 + 16 * sizes.length;
const table = [], body = [];
for (const n of sizes) {
  const blob = blobs[`favicon-${n}.png`], e = Buffer.alloc(16);
  e.writeUInt8(n, 0); e.writeUInt8(n, 1); e.writeUInt16LE(1, 4); e.writeUInt16LE(32, 6);
  e.writeUInt32LE(blob.length, 8); e.writeUInt32LE(offset, 12);
  offset += blob.length; table.push(e); body.push(blob);
}
const ico = Buffer.concat([header, ...table, ...body]);
writeFileSync(join(logo, "favicon.ico"), ico);

// The web app's copies.
const app = join(repo, "apps/web/src/app");
writeFileSync(join(app, "favicon.ico"), ico);
writeFileSync(join(app, "icon.svg"), svgs["favicon.svg"]);
writeFileSync(join(app, "apple-icon.png"), blobs["apple-touch-icon.png"]);
writeFileSync(
  join(repo, "apps/web/src/features/shell/logo-data.ts"),
  `// Generated by docs/design/logo/tools/build.mjs from the Outfit ExtraBold outlines. Don't edit by hand.\n` +
    `export const LOGO = ${JSON.stringify(web, null, 2)} as const;\n`,
);

console.log(`✓ ${Object.keys(svgs).length} svg, ${Object.keys(pngs).length - 3} png, favicon.ico, web app icons and logo-data.ts`);
